export const money = (value: number) =>
  new Intl.NumberFormat('en-IN', { style: 'currency', currency: 'INR', maximumFractionDigits: 2 }).format(value)

export function getProductTiers(product: Product): WholesaleTier[] {
  if (product.tiers && product.tiers.length > 0) return product.tiers
  const p1 = product.price
  const p2 = Math.round(product.price * 0.92 * 100) / 100
  const p3 = Math.round(product.price * 0.84 * 100) / 100
  return [
    { minQty: 1, maxQty: 2, label: '1-2 units', price: p1, discountPct: Math.round(((product.mrp - p1) / product.mrp) * 100) },
    { minQty: 3, maxQty: 5, label: '3-5 units', price: p2, discountPct: Math.round(((product.mrp - p2) / product.mrp) * 100) },
    { minQty: 6, label: '6+ units', price: p3, discountPct: Math.round(((product.mrp - p3) / product.mrp) * 100) },
  ]
}

export function unitPrice(product: Product, quantity: number, customerType: 'retail' | 'wholesale' = 'retail') {
  const tiers = getProductTiers(product)
  const matchedTier = [...tiers].reverse().find(t => quantity >= t.minQty)
  let basePrice = matchedTier ? matchedTier.price : product.price
  if (customerType === 'wholesale') {
    basePrice = Math.round(basePrice * 0.95 * 100) / 100
  }
  return basePrice
}
